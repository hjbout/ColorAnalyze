# Writes Sources/ColorCore/GradePreviewTables.swift from the calibration fit (run fit14.py first).
import numpy as np
d=np.load('model_final_inputs.npz')
xs,K,hs,D,M=d['xs'],d['K'],d['hs'],d['D'],d['M']
order=np.argsort(hs); hs=hs[order]; D=D[order]
Minv=np.linalg.inv(M)
def arr(v): return '['+', '.join(f'{x:.6f}' for x in v)+']'
def mat(m): return '[\n        '+',\n        '.join(arr(r) for r in m)+',\n    ]'
src=f'''// Generated by calibration/emit_tables.py from PhotoLab 10.1 exports of calibration/chart.jpg. Do not edit by hand.
//
// What the measurements say (see README, "Calibrating the preview"): Color Grading acts as a curve per channel in
// a linear RGB space with Rec.2020 primaries. Every tonal range adds, to each channel c, `saturation/100 × K(x_c) × n_c(hue)`,
// where x_c is the channel's own value. K is a bump per range (zero at black and at white); n is a vector in
// the (red, green, blue) channels that turns once around with the hue; it was measured at ten hues and is interpolated between them.
extension GradePreview {{
    /// sRGB-linear → Rec.2020-linear (neutrals stay neutral) and back.
    static let toWide: [[Float]] = {mat(M)}
    static let fromWide: [[Float]] = {mat(Minv)}
    /// Channel values (Rec.2020-linear) at which the curves were measured, black … white.
    static let curveNodes: [Float] = {arr(xs)}
    /// Added to a channel at saturation 100 and hue 231 (blue), per node: shadows, midtones, highlights.
    static let curves: [[Float]] = {mat(K)}
    /// Hues (PhotoLab's Hue field, degrees) at which n was measured, ascending.
    static let hueNodes: [Float] = {arr(hs)}
    /// n at those hues, normalised so that blue (231) adds 1 to the blue channel.
    static let hueVectors: [[Float]] = {mat(D)}
}}
'''
open('../Sources/ColorCore/GradePreviewTables.swift','w').write(src)
print('written;',len(hs),'hue nodes')
