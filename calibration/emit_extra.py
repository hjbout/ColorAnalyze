# Writes Sources/ColorCore/GradePreviewExtraTables.swift: the Luminance curves per range, the Master curves, and the Balance warp,
# measured from exports F1…F5, B1…B6 (see README). Run from calibration/.
exec(open('fit_extra.py').read())
g = lambda n, c: wide(load(n))[:17, c] - base[:17, c]
lum = np.stack([g('F3-shadows-lum60', 1), g('F4-mids-lum60', 1), g('F5-highs-lum60', 1)]) / 0.6
masterTint = g('F1-master-231-100', 2)          # blue channel at hue 231: n_blue = 1
masterLum = g('F2-master-lum60', 1) / 0.6
def arr(v): return '[' + ', '.join(f'{x:.6f}' for x in v) + ']'
src = f'''// Generated by calibration/emit_extra.py from PhotoLab 10.1 exports of calibration/chart.jpg. Do not edit by hand.
//
// Color Grading beyond Hue and Saturation of the three ranges (see README, "Calibrating the preview"):
// - Luminance of a range adds the same value to every channel: `luminance/100 × L(x_c)`, with L measured per range
//   (about 4% above the Saturation curves).
// - Master (the Global wheel) has its own curves, 3 to 14% above the sum of the three ranges.
// - Balance does not change the size of the effect, only how the three ranges share it: the ranges divide a total
//   that stays the same, and Balance slides their division along the channel value (in x^0.4167) by `balanceStep` per unit.
extension GradePreview {{
    /// Added to a channel at Luminance 100: shadows, midtones, highlights (same nodes as `curves`).
    static let luminanceCurves: [[Float]] = [
        {arr(lum[0])},
        {arr(lum[1])},
        {arr(lum[2])},
    ]
    /// Master wheel at Saturation 100 and hue 231 (blue channel), and at Luminance 100.
    static let masterTintCurve: [Float] = {arr(masterTint)}
    static let masterLuminanceCurve: [Float] = {arr(masterLum)}
    /// Balance: shift of the division of the ranges, per Balance unit, in channel value ^ `balanceGamma`.
    static let balanceGamma: Float = 0.4167
    static let balanceStep: Float = 0.0017
}}
'''
open('../Sources/ColorCore/GradePreviewExtraTables.swift', 'w').write(src)
print('written')

# ---- Master tint per hue: what each channel gets from a grey ramp, at Saturation 100 (second series, 11 October 2026)
master_files = [(0.0, 'M-master-0-100'), (36.0, 'R1-master-36-100'), (58.0, 'M-master-58-100'), (80.0, 'M-master-80-100'), (104.0, 'M-master-104-100'),
                (130.0, 'M-master-130-100'), (160.0, 'M-master-160-100'), (200.0, 'M-master-200-100'), (231.0, 'F1-master-231-100'), (270.0, 'M-master-270-100'),
                (312.0, 'M-master-312-100'), (340.0, 'M-master-340-100')]
mhues = [h for h, _ in master_files]
table = np.stack([(wide(load(f))[:17] - base[:17]).T for _, f in master_files])   # hue, channel, node
src2 = f'''// Generated by calibration/emit_extra.py from PhotoLab 10.1 exports of calibration/chart.jpg. Do not edit by hand.
//
// The Master wheel at Saturation 100: what the grey ramp (Rec.2020-linear, the same nodes as `curveNodes`) gets added to its red,
// green and blue channel at twelve hues. Master is not the sum of the three ranges and its channels do not share one curve, so
// it is measured per hue and channel and interpolated between the hues.
extension GradePreview {{
    static let masterHues: [Float] = {arr(mhues)}
    /// [hue][channel][node]
    static let masterTable: [[[Float]]] = [
''' + ''.join('        [\n' + ''.join(f'            {arr(table[h][c])},\n' for c in range(3)) + '        ],\n' for h in range(len(mhues))) + '''    ]
}
'''
open('../Sources/ColorCore/GradePreviewMasterTable.swift', 'w').write(src2)
print('master table written', table.shape)

# ---- Selective Tone (Light palette): Blacks and Shadows, as a curve of the mean of the three channels (linear sRGB)
gx = base[:17, 1]
def tone(f): return load(f)[:17].mean(1) - base_lin_mean
base_lin_mean = load('E0-baseline')[:17].mean(1)
tones = {name: tone(f) for name, f in [('blacksPlus', 'T-blacks-100'), ('blacksMinus', 'T-blacks-m100'),
                                        ('shadowsPlus', 'T-shadows-100'), ('shadowsMinus', 'T-shadows-m100')]}
src3 = f'''// Generated by calibration/emit_extra.py from PhotoLab 10.1 exports of calibration/chart.jpg. Do not edit by hand.
//
// Selective Tone of the Light palette, Blacks and Shadows at +100 and -100: what the grey ramp (linear sRGB, the same nodes as
// `curveNodes` but read from the unedited chart, so these are values of the chart's greys) gets added. A colored pixel is
// scaled by the gain of the mean of its three channels (measured: error 1.5 against an effect of 6.7 for Blacks +100); the
// sliders add up and are about linear in between (+50 gives 0.4 to 0.55 of +100).
extension GradePreview {{
    static let toneNodes: [Float] = {arr(base_lin_mean)}
    static let blacksPlus: [Float] = {arr(tones['blacksPlus'])}
    static let blacksMinus: [Float] = {arr(tones['blacksMinus'])}
    static let shadowsPlus: [Float] = {arr(tones['shadowsPlus'])}
    static let shadowsMinus: [Float] = {arr(tones['shadowsMinus'])}
}}
'''
open('../Sources/ColorCore/GradePreviewToneTable.swift', 'w').write(src3)
print('tone table written')
