import ColorCore
import SwiftUI

/// Everything the series overview shows, captured at export time.
struct SeriesReportData {
    struct Photo {
        var name: String
        var thumbnail: CGImage
        var colors: [SeriesColor]
        var consistency: PhotoConsistency
    }

    var date: Date
    var photos: [Photo]
    var palette: [SharedColor]
    var colorsPerPhoto: Int
    /// "Moderate" / "Strong" when subject weighting was used.
    var weighting: String?
    var hueSpace: HueSpace
    var averageScore: Int?
    /// What the series should feel like.
    var intention: String?
}

/// One image summarizing a series: the shared palette and the wheel on top, then a card for
/// every photo with its palette strip, consistency score and alignment suggestion.
struct SeriesReportView: View {
    let data: SeriesReportData

    private let margin: CGFloat = 36
    private let wheelSide: CGFloat = 480
    private let wheelBox: CGFloat = 540
    private let columns = 3
    private let gap: CGFloat = 24
    private let totalWidth: CGFloat = 1808

    private var contentWidth: CGFloat { totalWidth - 2 * margin }
    private var cardWidth: CGFloat { (contentWidth - CGFloat(columns - 1) * gap) / CGFloat(columns) }

    var body: some View {
        VStack(alignment: .leading, spacing: 28) {
            header
            HStack(alignment: .top, spacing: 36) {
                wheel.frame(width: wheelBox)
                palette
            }
            VStack(alignment: .leading, spacing: 12) {
                Text("Photos")
                    .font(.system(size: 17, weight: .semibold))
                photoGrid
            }
            footer
        }
        .padding(margin)
        .frame(width: totalWidth, alignment: .topLeading)
        .background(Color.white)
    }

    // MARK: Header & footer

    private var header: some View {
        HStack(alignment: .top) {
            VStack(alignment: .leading, spacing: 3) {
                Text("Series overview")
                    .font(.system(size: 28, weight: .bold))
                Text("\(data.photos.count) photos · \(data.palette.count)-color shared palette · up to \(data.colorsPerPhoto) colors per photo · \(data.date.formatted(date: .long, time: .shortened))"
                     + (data.weighting.map { " · weighted toward the subject (\($0.lowercased()))" } ?? ""))
                    .font(.system(size: 14))
                    .foregroundStyle(.secondary)
                if let intention = data.intention {
                    Text("Intention: “\(intention)”")
                        .font(.system(size: 15).italic())
                        .padding(.top, 4)
                }
            }
            Spacer()
            if let average = data.averageScore {
                VStack(alignment: .trailing, spacing: 6) {
                    Text("Average consistency")
                        .font(.system(size: 13))
                        .foregroundStyle(.secondary)
                    Text("\(average)")
                        .font(.system(size: 26, weight: .bold, design: .rounded).monospacedDigit())
                        .foregroundStyle(.white)
                        .padding(.horizontal, 16)
                        .padding(.vertical, 3)
                        .background(average >= 80 ? Color.green : average >= 60 ? Color.orange : Color.red, in: Capsule())
                }
            }
        }
    }

    private var footer: some View {
        Text("Generated by ColorAnalyze. DxO channels and alignment suggestions are approximations — a starting point for color grading, not exact settings.")
            .font(.system(size: 11))
            .foregroundStyle(.secondary)
            .frame(width: contentWidth, alignment: .leading)
    }

    // MARK: Wheel

    private var wheel: some View {
        let center = CGPoint(x: wheelBox / 2, y: wheelBox / 2)
        let radius = wheelSide / 2
        let space = data.hueSpace
        let position = { (color: SRGBColor) -> CGPoint in
            let hsb = color.hsb
            return WheelGeometry.point(rgbHue: hsb.h, space: space, saturation: hsb.s, center: center, radius: radius)
        }
        return VStack(spacing: 8) {
            ZStack {
                Image(decorative: WheelGeometry.wheelImage(for: space), scale: 1)
                    .resizable()
                    .frame(width: wheelSide, height: wheelSide)
                    .shadow(color: .black.opacity(0.25), radius: 6)
                ForEach(Array(data.photos.enumerated()), id: \.offset) { _, photo in
                    ForEach(Array(photo.colors.enumerated()), id: \.offset) { _, color in
                        let diameter = 7 + 14 * sqrt(color.share)
                        Circle()
                            .fill(color.color.swiftUIColor)
                            .overlay(Circle().strokeBorder(.white, lineWidth: 1))
                            .frame(width: diameter, height: diameter)
                            .shadow(color: .black.opacity(0.4), radius: 1.5)
                            .opacity(0.9)
                            .position(position(color.color))
                    }
                }
                ForEach(Array(data.palette.enumerated()), id: \.offset) { index, shared in
                    MarkerBadge(number: index + 1, color: shared.color, diameter: 22 + 30 * sqrt(shared.share))
                        .position(position(shared.color))
                }
            }
            .frame(width: wheelBox, height: wheelBox)
            Text("Badges: shared palette. Dots: the colors of each photo (\(space.displayName) wheel).")
                .font(.system(size: 11))
                .foregroundStyle(.secondary)
        }
    }

    // MARK: Palette

    private var palette: some View {
        let maxShare = max(0.01, data.palette.map(\.share).max() ?? 0.01)
        let paletteWidth = contentWidth - wheelBox - 36
        let columnWidth = (paletteWidth - 36) / 2
        let rows = stride(from: 0, to: data.palette.count, by: 2).map { Array(data.palette.enumerated())[$0..<min($0 + 2, data.palette.count)] }
        return VStack(alignment: .leading, spacing: 0) {
            Text("Shared palette")
                .font(.system(size: 17, weight: .semibold))
                .padding(.bottom, 8)
            ForEach(Array(rows.enumerated()), id: \.offset) { _, row in
                Divider()
                HStack(alignment: .top, spacing: 36) {
                    ForEach(Array(row), id: \.offset) { index, shared in
                        PaletteRow(number: index + 1, shared: shared, maxShare: maxShare)
                            .frame(width: columnWidth, alignment: .leading)
                    }
                    if row.count == 1 { Spacer(minLength: 0) }
                }
                .padding(.vertical, 8)
            }
            guide
                .padding(.top, 28)
        }
        .frame(width: paletteWidth, alignment: .topLeading)
    }

    private var guide: some View {
        let lines = [
            "Score: 100 means a photo's colors coincide with the shared palette (green from 80, orange from 60, red below).",
            "Presence: in how many photos a color close to the palette color occurs; orange when fewer than half.",
            "Δ is the mean color distance (OKLab) to the palette; \"without a counterpart\" is the share of a photo with no close palette color, such as a unique subject.",
            "Suggestion: an average over the colors that match the palette — hue in sRGB degrees; positive saturation or lightness means the photo is less saturated or darker than the series. Shown when at least 60% of the photo matches.",
        ]
        return VStack(alignment: .leading, spacing: 6) {
            Text("Reading the overview")
                .font(.system(size: 14, weight: .semibold))
            ForEach(Array(lines.enumerated()), id: \.offset) { _, line in
                Text("•  " + line)
                    .font(.system(size: 12))
                    .foregroundStyle(.secondary)
                    .fixedSize(horizontal: false, vertical: true)
            }
        }
    }

    // MARK: Photos

    private var photoGrid: some View {
        let rows = stride(from: 0, to: data.photos.count, by: columns).map {
            Array(data.photos[$0..<min($0 + columns, data.photos.count)])
        }
        return VStack(alignment: .leading, spacing: 16) {
            ForEach(Array(rows.enumerated()), id: \.offset) { _, row in
                HStack(alignment: .top, spacing: gap) {
                    ForEach(Array(row.enumerated()), id: \.offset) { _, photo in
                        SeriesReportCard(photo: photo)
                            .frame(width: cardWidth, alignment: .leading)
                    }
                }
            }
        }
    }
}

private struct SeriesReportCard: View {
    let photo: SeriesReportData.Photo

    var body: some View {
        let c = photo.consistency
        HStack(alignment: .top, spacing: 12) {
            Image(decorative: photo.thumbnail, scale: 1)
                .resizable()
                .aspectRatio(contentMode: .fill)
                .frame(width: 150, height: 106)
                .clipShape(RoundedRectangle(cornerRadius: 6))
            VStack(alignment: .leading, spacing: 5) {
                HStack {
                    Text(photo.name)
                        .font(.system(size: 14, weight: .semibold))
                        .lineLimit(1)
                        .truncationMode(.middle)
                    Spacer(minLength: 4)
                    ScoreBadge(score: c.score)
                }
                PaletteStrip(colors: photo.colors)
                    .frame(height: 14)
                Text(String(format: "Δ %.3f · %.0f%% without a counterpart in the palette", c.meanDeltaE, c.unmatchedShare * 100))
                    .font(.system(size: 11))
                    .foregroundStyle(.secondary)
                if c.hasSuggestion {
                    Text(seriesSuggestion(c) ?? "Matches the series")
                        .font(.system(size: 12, weight: .medium))
                        .foregroundStyle(seriesSuggestion(c) == nil ? .green : .primary)
                } else {
                    Text("Too different from the series to suggest an alignment")
                        .font(.system(size: 12, weight: .medium))
                        .foregroundStyle(.orange)
                }
            }
        }
    }
}
