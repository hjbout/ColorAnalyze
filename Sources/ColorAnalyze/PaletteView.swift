import ColorCore
import SwiftUI

/// What the palette image shows.
struct PaletteData {
    struct Entry {
        var number: Int
        var color: SRGBColor
        /// Share of the photo (0...1).
        var share: Double
    }

    var title: String
    var subtitle: String
    var entries: [Entry]
}

/// The palette as one image to keep next to a moodboard or to hand over: a bar with every color as wide
/// as its share, and below it a card per color with number, hex and share.
struct PaletteView: View {
    let data: PaletteData

    private let margin: CGFloat = 40
    private let totalWidth: CGFloat = 1600
    private var contentWidth: CGFloat { totalWidth - 2 * margin }

    var body: some View {
        VStack(alignment: .leading, spacing: 22) {
            VStack(alignment: .leading, spacing: 3) {
                Text(data.title)
                    .font(.system(size: 26, weight: .bold))
                    .lineLimit(1)
                Text(data.subtitle)
                    .font(.system(size: 14))
                    .foregroundStyle(.secondary)
            }
            bar
            cards
            Text("Generated by ColorAnalyze. Colors are sRGB; the bar is as wide as each color's share of the photo.")
                .font(.system(size: 11))
                .foregroundStyle(.secondary)
        }
        .padding(margin)
        .frame(width: totalWidth, alignment: .topLeading)
        .background(Color.white)
    }

    private var bar: some View {
        let total = max(data.entries.reduce(0) { $0 + $1.share }, 0.0001)
        return HStack(spacing: 0) {
            ForEach(Array(data.entries.enumerated()), id: \.offset) { _, entry in
                Rectangle()
                    .fill(entry.color.swiftUIColor)
                    .frame(width: contentWidth * entry.share / total)
            }
        }
        .frame(width: contentWidth, height: 110, alignment: .leading)
        .clipShape(RoundedRectangle(cornerRadius: 10))
    }

    private var cards: some View {
        let count = max(data.entries.count, 1)
        let gap: CGFloat = 14
        let cardWidth = (contentWidth - CGFloat(count - 1) * gap) / CGFloat(count)
        return HStack(alignment: .top, spacing: gap) {
            ForEach(Array(data.entries.enumerated()), id: \.offset) { _, entry in
                VStack(alignment: .leading, spacing: 6) {
                    RoundedRectangle(cornerRadius: 8)
                        .fill(entry.color.swiftUIColor)
                        .frame(height: 150)
                        .overlay(alignment: .topLeading) {
                            Text("\(entry.number)")
                                .font(.system(size: 13, weight: .bold, design: .rounded))
                                .foregroundStyle(entry.color.prefersDarkText ? Color.black.opacity(0.7) : .white)
                                .padding(8)
                        }
                    Text(entry.color.hex)
                        .font(.system(size: min(17, cardWidth / 6.5), weight: .semibold, design: .monospaced))
                    Text(String(format: "%.1f%%", entry.share * 100))
                        .font(.system(size: 13).monospacedDigit())
                        .foregroundStyle(.secondary)
                }
                .frame(width: cardWidth, alignment: .leading)
            }
        }
    }
}

extension ReportRenderer {
    static func pngData(for data: PaletteData) -> Data? {
        let renderer = ImageRenderer(content: PaletteView(data: data).environment(\.colorScheme, .light))
        renderer.scale = scale
        guard let image = renderer.cgImage else { return nil }
        return NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:])
    }
}
